export function colorKey(pocket: string): 'colorRed' | 'colorBlack' | 'colorGreen' {
  if (pocket === '0' || pocket === '00') return 'colorGreen';
  const reds = new Set([1, 3, 5, 7, 9, 12, 14, 16, 18, 19, 21, 23, 25, 27, 30, 32, 34, 36]);
  return reds.has(Number(pocket)) ? 'colorRed' : 'colorBlack';
}

