const STORAGE_KEY = 'harry-story-lang';

export function matchLocale(raw: string | null | undefined): Locale {
  const value = (raw ?? '').trim().toLowerCase();
  if (!value) return 'en';
  if (value.startsWith('zh')) return 'zh-CN';
  const base = value.split('-')[0] ?? '';
  const hit = LOCALES.find((locale) => locale.toLowerCase() === value || locale.toLowerCase() === base);
  return hit ?? 'en';
}

function readSaved(): Locale | null {
  try {
    return matchLocale(localStorage.getItem(STORAGE_KEY));
  } catch {
    return null;
  }
}

function detect(): Locale {
  if (typeof navigator === 'undefined') return 'en';
  const saved = readSaved();
  if (saved && localStorage.getItem(STORAGE_KEY)) return saved;
  return matchLocale(navigator.language);
}

let current: Locale = detect();
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return current;
}

export function setLocale(next: Locale): void {
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // The choice still applies for this visit.
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next;
  for (const listener of listeners) listener();
}

export function onLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const pack = dictionaries[current];
  let text = pack[key] ?? dictionaries.en[key];
  if (!vars) return text;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

