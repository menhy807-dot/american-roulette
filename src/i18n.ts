export type GameNotice =
  | { k: 'idle' }
  | { k: 'insufficient' }
  | { k: 'placed'; spot: string; amount: string; total: string }
  | { k: 'nothingUndo' }
  | { k: 'undone' }
  | { k: 'undoneMore'; total: string }
  | { k: 'emptyTable' }
  | { k: 'cleared' }
  | { k: 'needBet' }
  | { k: 'spinning' }
  | { k: 'wait' }
  | { k: 'reset' }
  | { k: 'imported' }
  | { k: 'outcome'; pocket: string; net: number; amount: string };

export function renderNotice(notice: GameNotice): string {
  switch (notice.k) {
    case 'idle': return t('idle');
    case 'insufficient': return t('insufficient');
    case 'placed': return t('placed', { title: spotTitle(notice.spot), amount: notice.amount, total: notice.total });
    case 'nothingUndo': return t('nothingUndo');
    case 'undone': return t('undone');
    case 'undoneMore': return t('undoneMore', { total: notice.total });
    case 'emptyTable': return t('emptyTable');
    case 'cleared': return t('cleared');
    case 'needBet': return t('needBet');
    case 'spinning': return t('spinningStatus');
    case 'wait': return t('wait');
    case 'reset': return t('resetDone');
    case 'imported': return t('importedStatus');
    case 'outcome': {
      const color = t(colorKey(notice.pocket));
      if (notice.net > 0) return t('outcomeWin', { pocket: notice.pocket, color, amount: notice.amount });
      if (notice.net < 0) return t('outcomeLose', { pocket: notice.pocket, color, amount: notice.amount });
      return t('outcomePush', { pocket: notice.pocket, color });
    }
    default: return t('idle');
  }
}

export function applyDom(root: ParentNode = document): void {
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n as MessageKey | undefined;
    if (key && key in en) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.dataset.i18nAria as MessageKey | undefined;
    if (key && key in en) el.setAttribute('aria-label', t(key));
  });
}

export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  'zh-CN': '中文',
  ja: '日本語',
  ko: '한국어',
  de: 'Deutsch',
  es: 'Español',
  pt: 'Português',
  it: 'Italiano',
};

export function mountLanguageMenu(root: HTMLElement): void {
  const button = root.querySelector<HTMLButtonElement>('[data-lang-button]');
  const list = root.querySelector<HTMLElement>('[data-lang-list]');
  if (!button || !list) return;
  const paint = () => {
    button.textContent = LOCALE_NAMES[current];
    list.replaceChildren();
    for (const locale of LOCALES) {
      const item = document.createElement('li');
      const choice = document.createElement('button');
      choice.type = 'button';
      choice.textContent = LOCALE_NAMES[locale];
      choice.setAttribute('aria-pressed', locale === current ? 'true' : 'false');
      choice.addEventListener('click', () => {
        setLocale(locale);
        list.hidden = true;
        button.setAttribute('aria-expanded', 'false');
      });
      item.appendChild(choice);
      list.appendChild(item);
    }
  };
  button.addEventListener('click', () => {
    list.hidden = !list.hidden;
    button.setAttribute('aria-expanded', list.hidden ? 'false' : 'true');
  });
  onLocale(paint);
  paint();
}
